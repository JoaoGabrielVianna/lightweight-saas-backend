// TestService_PropagatesRepositoryFailures pins that an unexpected storage
// error is passed up unchanged rather than being flattened into a domain
// error. The handler is what turns it into internal_error, so flattening here
// would lose the cause before it could be logged.
func TestService_PropagatesRepositoryFailures(t *testing.T) {
	boom := errors.New("connection reset")
	repo := newFakeRepository(activeWorkspace(fixtureIDProd, "production", "Production"))
	repo.failWith = boom
	svc := NewService(repo, &fakeRunner{}, &fakeAuditWriter{})
	svc.now = fixedClock()

	calls := map[string]func() error{
		"Create": func() error {
			_, err := svc.Create(ctx(), CreateInput{Name: "X", Slug: "x"}, testEvent(audit.ActionWorkspaceCreated))
			return err
		},
		"Get":  func() error { _, err := svc.Get(ctx(), "ws_"+fixtureIDProd); return err },
		"List": func() error { _, err := svc.List(ctx(), "active"); return err },
		"UpdateName": func() error {
			_, err := svc.UpdateName(ctx(), "ws_"+fixtureIDProd, "Y", testEvent(audit.ActionWorkspaceRenamed))
			return err
		},
		"Archive": func() error {
			_, err := svc.Archive(ctx(), "ws_"+fixtureIDProd, testEvent(audit.ActionWorkspaceArchived))
			return err
		},
	}

	for name, call := range calls {
		t.Run(name, func(t *testing.T) {
			if err := call(); !errors.Is(err, boom) {
				t.Errorf("error = %v, want the repository's error unwrapped", err)
			}
		})
	}
}

