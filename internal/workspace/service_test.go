// TestCreate_GeneratesIDBeforeInsert pins that the id exists on the returned
// value and is a real UUID — the whole reason ids are generated by the
// application rather than by the database.
func TestCreate_GeneratesIDBeforeInsert(t *testing.T) {
	svc, _ := newTestService()

	first, err := svc.Create(ctx(), CreateInput{Name: "One", Slug: "one"}, testEvent(audit.ActionWorkspaceCreated))
	if err != nil {
		t.Fatalf("Create: %v", err)
	}
	second, err := svc.Create(ctx(), CreateInput{Name: "Two", Slug: "two"}, testEvent(audit.ActionWorkspaceCreated))
	if err != nil {
		t.Fatalf("Create: %v", err)
	}

	if first.ID == second.ID {
		t.Error("two workspaces got the same id")
	}
	for _, w := range []*Workspace{first, second} {
		if _, err := publicid.Parse(publicid.WorkspacePrefix, w.ID); err != nil {
			t.Errorf("id %q is not a valid UUID: %v", w.ID, err)
		}
		if !strings.HasPrefix(w.PublicID(), "ws_") {
			t.Errorf("PublicID() = %q, want a ws_ prefix", w.PublicID())
		}
	}
}

