// TestArchive_IsIdempotent is the retry-safety requirement: a client that
// times out and retries must get the same answer, not a spurious conflict.
func TestArchive_IsIdempotent(t *testing.T) {
	svc, _ := newTestService(activeWorkspace(fixtureIDProd, "production", "Production"))

	first, err := svc.Archive(ctx(), "ws_"+fixtureIDProd, testEvent(audit.ActionWorkspaceArchived))
	if err != nil {
		t.Fatalf("first Archive: %v", err)
	}

	for i := 0; i < 3; i++ {
		again, err := svc.Archive(ctx(), "ws_"+fixtureIDProd, testEvent(audit.ActionWorkspaceArchived))
		if err != nil {
			t.Fatalf("repeat Archive %d: %v", i, err)
		}
		if again.Status != StatusArchived {
			t.Errorf("repeat %d: status = %q, want archived", i, again.Status)
		}
		if !again.ArchivedAt.Equal(*first.ArchivedAt) {
			t.Errorf("repeat %d moved archived_at from %v to %v — the original timestamp must stand",
				i, first.ArchivedAt, again.ArchivedAt)
		}
	}
}

